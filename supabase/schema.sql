-- Numeração automática do lote quando o admin não informar.
create or replace function public.assign_lot_number()
returns trigger
language plpgsql
as $$
begin
  if new.n is null or new.n < 1 then
    select coalesce(max(n), 0) + 1 into new.n from public.lots;
  end if;
  return new;
end;
$$;
revoke all on function public.assign_lot_number() from public;

drop trigger if exists lots_assign_number on public.lots;
create trigger lots_assign_number
  before insert on public.lots
  for each row execute function public.assign_lot_number();

-- Substitui todas as fotos de um lote de forma atômica.
create or replace function public.replace_lot_photos(p_lot_id bigint, p_urls text[])
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  i integer;
  u text;
  total integer;
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem alterar fotos.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.lots where id = p_lot_id) then
    raise exception 'Lote não encontrado.' using errcode = 'P0002';
  end if;

  delete from public.lot_photos where lot_id = p_lot_id;
  total := coalesce(array_length(p_urls, 1), 0);

  if total > 0 then
    for i in 1..total loop
      u := btrim(coalesce(p_urls[i], ''));
      if u <> '' then
        insert into public.lot_photos (lot_id, url, position)
        values (p_lot_id, u, i - 1);
      end if;
    end loop;
  end if;
end;
$$;
revoke all on function public.replace_lot_photos(bigint, text[]) from public;
grant execute on function public.replace_lot_photos(bigint, text[]) to authenticated;

create or replace function public.update_my_name(p_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Faça login para atualizar o perfil.' using errcode = '42501';
  end if;
  if length(trim(coalesce(p_name, ''))) < 2 then
    raise exception 'Informe um nome válido.' using errcode = '22023';
  end if;
  update public.profiles
  set name = trim(p_name)
  where id = auth.uid();
end;
$$;
revoke all on function public.update_my_name(text) from public;
grant execute on function public.update_my_name(text) to authenticated;

-- Lance transacional: bloqueia o lote, valida o mínimo e grava o lance.
create or replace function public.place_bid(p_lot_id bigint, p_amount numeric)
returns public.bids
language plpgsql
security definer
set search_path = public
as $$
declare
  v_lot public.lots;
  v_current numeric(14,2);
  v_min numeric(14,2);
  v_bid public.bids;
begin
  if auth.uid() is null then
    raise exception 'Faça login para dar lances.' using errcode = '42501';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Valor de lance inválido.' using errcode = '22023';
  end if;

  select * into v_lot from public.lots where id = p_lot_id for update;
  if not found then
    raise exception 'Lote não encontrado.' using errcode = 'P0002';
  end if;
  if v_lot.status <> 'published' then
    raise exception 'Este lote não está aberto para lances.' using errcode = '22023';
  end if;
  if v_lot.ends_at is not null and v_lot.ends_at <= now() then
    raise exception 'O prazo deste lote terminou.' using errcode = '22023';
  end if;

  select coalesce(max(amount), 0) into v_current
  from public.bids
  where lot_id = p_lot_id and status = 'active';

  v_min := greatest(v_lot.price, coalesce(v_lot.current_price, 0), v_current) + v_lot.increment;
  if round(p_amount, 2) < v_min then
    raise exception 'O lance mínimo é %.', v_min using errcode = '22023';
  end if;

  insert into public.bids (lot_id, user_id, amount)
  values (p_lot_id, auth.uid(), round(p_amount, 2))
  returning * into v_bid;

  update public.lots
  set current_price = v_bid.amount,
      bid_count = coalesce(bid_count, 0) + 1
  where id = p_lot_id;

  insert into public.audit_logs (actor_id, action, entity, entity_id, payload)
  values (
    auth.uid(),
    'bid.created',
    'bids',
    v_bid.id::text,
    jsonb_build_object('lot_id', p_lot_id, 'amount', v_bid.amount)
  );

  return v_bid;
end;
$$;
revoke all on function public.place_bid(bigint, numeric) from public;
grant execute on function public.place_bid(bigint, numeric) to authenticated;

-- Histórico público sem expor e-mail/ID; retorna apenas o primeiro nome.
create or replace function public.lot_bid_history(p_lot_id bigint)
returns table (display_name text, amount numeric, created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select
    coalesce(nullif(split_part(p.name, ' ', 1), ''), 'Participante') as display_name,
    b.amount,
    b.created_at
  from public.bids b
  left join public.profiles p on p.id = b.user_id
  where b.lot_id = p_lot_id
    and b.status = 'active'
    and exists (
      select 1 from public.lots l
      where l.id = p_lot_id
        and (l.status = 'published' or public.is_admin())
    )
  order by b.created_at desc
  limit 100;
$$;
revoke all on function public.lot_bid_history(bigint) from public;
grant execute on function public.lot_bid_history(bigint) to anon, authenticated;

