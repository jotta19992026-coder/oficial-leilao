-- ------------------------------------------------------------
-- Lotes (o site usa estes campos para montar cards e detalhe)
-- ------------------------------------------------------------
create table if not exists public.lots (
  id bigint generated by default as identity (start with 10000) primary key,
  auction_id uuid references public.auctions(id) on delete set null,
  n integer,
  title text not null,
  description text,
  obs text,
  category text not null check (category in ('carro', 'moto', 'pesado', 'nautico', 'imovel', 'equipamento')),
  year text,
  km text,
  city text,
  price numeric(14,2) not null check (price >= 0),
  increment numeric(14,2) not null default 100 check (increment > 0),
  media text not null default 'c1',
  auction_num integer,
  auction_date date,
  auction_time text,
  auction_label text,
  ends_at timestamptz,
  ends_label text,
  status public.lot_status not null default 'draft',
  featured boolean not null default false,
  bid_count integer not null default 0,
  current_price numeric(14,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

